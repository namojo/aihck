def P(text: str, style=body):
    return Paragraph(text, style)


def req_table(rows: list[tuple[str, str, str, str, str]]):
    header = ["요구사항 고유번호", "요구사항 명칭", "정의", "세부내용", "산출정보"]
    data = [[Paragraph(h, cellb) for h in header]]
    for r in rows:
        data.append([Paragraph(c, cell) for c in r])
    t = Table(data, colWidths=[24 * mm, 26 * mm, 40 * mm, 62 * mm, 24 * mm], repeatRows=1)
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#DDDDDD")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


def simple_table(header: list[str], rows: list[list[str]], widths: list[float]):
    data = [[Paragraph(h, cellb) for h in header]] + [[Paragraph(c, cell) for c in r] for r in rows]
    t = Table(data, colWidths=[w * mm for w in widths], repeatRows=1)
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#DDDDDD")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return t


