BOLD_CANDIDATES = [Path.home() / ".local/share/fonts/pretendard/Pretendard-Bold.ttf"]


def _font() -> tuple[str, str]:
    for p in FONT_CANDIDATES:
        if p.exists() and p.suffix == ".ttf":
            pdfmetrics.registerFont(TTFont("KR", str(p)))
            bold = "KR"
            for b in BOLD_CANDIDATES:
                if b.exists():
                    pdfmetrics.registerFont(TTFont("KR-B", str(b)))
                    bold = "KR-B"
            return "KR", bold
    raise SystemExit("한글 TTF 폰트를 찾지 못했다. Pretendard 또는 NanumGothic을 설치할 것")


